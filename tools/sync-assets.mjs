// Generate one content-based browser revision for the complete local module graph.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve, relative, join } from "node:path";
import { pathToFileURL } from "node:url";

export async function applicationFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => {
      const path = join(directory, entry.name);
      return entry.isDirectory()
        ? applicationFiles(path)
        : path.endsWith(".js")
          ? [path]
          : [];
    }),
  );
  return nested.flat().sort();
}

export async function assetManifest(root = process.cwd()) {
  const files = await applicationFiles(join(root, "src"));
  const hash = createHash("sha256");
  for (const file of [...files, join(root, "style.css")]) {
    hash.update(relative(root, file).replaceAll("\\", "/"));
    hash.update(await readFile(file));
  }
  const { version } = JSON.parse(
    await readFile(join(root, "package.json"), "utf8"),
  );
  const build = `${version}-${hash.digest("hex").slice(0, 12)}`;
  const imports = Object.fromEntries(
    files.map((file) => {
      const path = `./${relative(root, file).replaceAll("\\", "/")}`;
      return [path, `${path}?v=${build}`];
    }),
  );
  return { build, imports };
}

export async function syncAssets(root = process.cwd()) {
  const file = join(root, "index.html");
  const html = await readFile(file, "utf8");
  const existing = JSON.parse(
    html.match(/<script type="importmap">([\s\S]*?)<\/script>/)[1],
  );
  const manifest = await assetManifest(root);
  const external = Object.fromEntries(
    Object.entries(existing.imports).filter(
      ([key]) => !key.startsWith("./src/"),
    ),
  );
  const imports = JSON.stringify(
    { imports: { ...external, ...manifest.imports } },
    null,
    2,
  );
  const block = [
    `<meta name="app-build" content="${manifest.build}" />`,
    `    <link rel="stylesheet" href="./style.css?v=${manifest.build}" />`,
    "    <!-- Generated by npm run assets; keeps lazy imports on the same revision. -->",
    '    <script type="importmap">',
    ...imports.split("\n").map((line) => `      ${line}`),
    "    </script>",
    `    <script type="module" src="./src/main.js?v=${manifest.build}"></script>`,
  ].join("\n");
  const next = html.replace(
    /<meta\s+name="app-build"[\s\S]*?<script\s+type="module"\s+src="\.\/src\/main\.js[^"]*"\s*><\/script>/,
    block,
  );
  if (next === html && !html.includes(manifest.build))
    throw new Error("Cannot locate generated assets in index.html");
  if (next !== html) await writeFile(file, next);
  return manifest;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const { build } = await syncAssets();
  console.log(`Browser assets synchronized: ${build}`);
}
